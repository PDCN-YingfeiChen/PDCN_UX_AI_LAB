import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const args = process.argv.slice(2);
const inputPath = readArgValue(args, "--input") || path.join("generated", "agent-brief.json");
const outPath = readArgValue(args, "--out") || path.join("generated", "figma-mcp-render.js");

const brief = await readJsonRequired(inputPath);
validateBrief(brief, inputPath);

const script = buildFigmaScript(brief);

await mkdir(path.dirname(outPath), { recursive: true });
await writeFile(outPath, script, "utf8");

console.log(`Built Figma MCP screen script: ${outPath}`);
console.log(`Screen: ${brief.screen}`);
console.log("Send this script to figma-ui-mcp figma_write.");

async function readJsonRequired(filePath) {
  const raw = await readFile(filePath, "utf8");
  return JSON.parse(raw);
}

function validateBrief(brief, filePath) {
  if (!brief || typeof brief !== "object" || Array.isArray(brief)) {
    throw new Error(`${filePath} must contain a JSON object.`);
  }
  if (!brief.screen || typeof brief.screen !== "string") {
    throw new Error(`${filePath} must include a string screen field.`);
  }
  if (brief.device !== undefined && typeof brief.device !== "string") {
    throw new Error(`${filePath} device must be a string when provided.`);
  }
  if (brief.data !== undefined && (!brief.data || typeof brief.data !== "object" || Array.isArray(brief.data))) {
    throw new Error(`${filePath} data must be an object when provided.`);
  }
}

function buildFigmaScript(brief) {
  return `// Auto-generated by scripts/build-mcp-screen-script.mjs.\n// Execute this whole file with figma-ui-mcp's figma_write tool.\n// Requires scripts/patch-figma-ui-mcp.mjs to have patched figma-ui-mcp with renderPdcnScreen.\n\nconst result = await figma.renderPdcnScreen(${JSON.stringify(brief, null, 2)});\n\nresult;\n`;
}

function readArgValue(argv, key) {
  const index = argv.findIndex((arg) => arg === key);
  if (index >= 0 && argv[index + 1]) {
    return argv[index + 1];
  }

  const prefixed = argv.find((arg) => arg.startsWith(`${key}=`));
  if (prefixed) {
    return prefixed.split("=")[1];
  }

  return null;
}
